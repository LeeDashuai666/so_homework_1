#!/usr/bin/env python3
"""Build single-kernel input, calibrate, and let BOLT inject the protection."""
import argparse
from datetime import datetime
from zoneinfo import ZoneInfo
import hashlib
import importlib.util
import json
import math
import os
from pathlib import Path
import random
import re
import shutil
import statistics
import subprocess

HERE = Path(__file__).resolve().parent
STAGE = HERE.parents[1]


def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def write(p, x): Path(p).write_text(json.dumps(x, indent=2)+'\n')


def median_ci(values, alpha=.05):
    x = sorted(values); n = len(x); k = 0
    for c in range(1, (n+1)//2+1):
        if sum(math.comb(n, j) for j in range(c))/2**n <= alpha/2: k = c
    return {'low': x[k-1] if k else 0, 'high': x[n-k] if k else None,
            'order_index': k, 'confidence_at_least': 1-alpha}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--bolt', type=Path, default=STAGE/'build/bin/llvm-bolt')
    p.add_argument('--compiler', default='clang++')
    p.add_argument('--calibration-blocks', type=int, default=9)
    args = p.parse_args()
    out = args.output.resolve(); out.mkdir(parents=True, exist_ok=False)
    allowed = sorted(os.sched_getaffinity(0)); os.sched_setaffinity(0, {allowed[min(2,len(allowed)-1)]})
    compiler = shutil.which(args.compiler)
    if not compiler: raise RuntimeError('compiler not found')
    bolt = args.bolt.resolve()
    helper = STAGE/'project/cmov_branchify/run.py'
    spec = importlib.util.spec_from_file_location('pipeline', helper)
    pipeline = importlib.util.module_from_spec(spec); spec.loader.exec_module(pipeline)
    protocol = {'started_at': datetime.now(ZoneInfo('Asia/Hong_Kong')).isoformat(),
                'scope': 'single-kernel input; runtime protection generated by BOLT',
                'compiler': subprocess.check_output([compiler, '--version'],text=True).splitlines()[0],
                'bolt_sha256': sha(bolt), 'runtime_archive_sha256':sha(bolt.parent.parent/'lib/libbolt_rt_cmov.a'), 'calibration_blocks': args.calibration_blocks,
                'sources': {n:sha(HERE/n) for n in ('runtime.h','cmov_abi.h','kernel.cpp','plain.cpp','entry.cpp','bench.cpp','build.py')},
                'calibration_cases': [[4096,83],[8192,1009]],
                'calibration_rule': 'both exact median 95% CI lower bounds >= 1.02',
                'common_options': pipeline.COMMON}
    write(out/'protocol.json', protocol)
    snapshot = out/'source'; snapshot.mkdir()
    for name in protocol['sources']: shutil.copy2(HERE/name, snapshot/name)
    commands = []
    def command(argv, name):
        argv = list(map(str,argv)); result = subprocess.run(argv,capture_output=True,text=True,timeout=240)
        (out/(name+'.log')).write_text(result.stdout+result.stderr)
        commands.append({'argv':argv,'returncode':result.returncode,'log':name+'.log'})
        write(out/'commands.json',commands)
        if result.returncode: raise RuntimeError('command failed: '+str(out/(name+'.log')))
        return result.stdout
    def run(binary, mode, case, size, seed, repeats=1):
        result = subprocess.run([str(binary),mode,case,str(size),str(seed),str(repeats)],capture_output=True,text=True,timeout=120)
        if result.returncode: raise RuntimeError(result.stderr[-2000:])
        return json.loads(result.stdout)
    objects=[]
    for name in ('kernel','plain','entry','bench'):
        obj=out/(name+'.o');objects.append(obj)
        command([compiler,'-O3','-g','-std=c++17','-c',HERE/(name+'.cpp'),'-o',obj],name+'-compile')
    original=out/'input'
    command([compiler,'-Wl,--emit-relocs',*objects,'-o',original],'link-input')
    command(['nm','-S',original],'input-symbols')
    symbols=(out/'input-symbols.log').read_text()
    if '__bolt_cmov_' in symbols: raise RuntimeError('input already contains runtime/clone')
    manifest=out/'sites.json'
    for kind in ('normal','probe'):
        inst=out/(kind+'.inst')
        flags=['-cmov-branchify-probe','-cmov-branchify-sites='+str(manifest)] if kind=='probe' else []
        command([bolt,original,'-instrument','-instrumentation-file='+str(out/(kind+'.fdata')),*flags,'-o',inst],kind+'-instrument')
        # Exercise the forwarding API as well as the kernel: BOLT lite mode
        # legitimately leaves unprofiled entry functions without a CFG.
        a=run(original,'guarded','train',4096,71);b=run(inst,'guarded','train',4096,71)
        if a['runs'][0]['checksum']!=b['runs'][0]['checksum']:raise RuntimeError('training output mismatch')
    profile=pipeline.predicate_profile(json.loads(manifest.read_text()),out/'probe.fdata')
    profile['sites']=[s for s in profile['sites'] if s['function']=='cmov_kernel_v1']
    if len(profile['sites'])!=1:raise RuntimeError('compiler did not emit the one supported group')
    write(out/'candidate-profile.json',profile)
    off=out/'off';candidate=out/'static-candidate';on=out/'on'
    base=['-data='+str(out/'normal.fdata'),*pipeline.COMMON]
    command([bolt,original,*base,'-o',off],'off')
    command([bolt,original,*base,'-cmov-branchify-candidate','-cmov-branchify-profile='+str(out/'candidate-profile.json'),'-o',candidate],'candidate')
    if not re.search(r'CMOV branchify: \d+ candidates, 1 converted',(out/'candidate.log').read_text()):
        raise RuntimeError('static candidate conversion failed')
    rng=random.Random(120711);calibration=[];raw=[]
    for size,seed in protocol['calibration_cases']:
        for binary in (off,candidate):run(binary,'off','low95',size,seed)
        ratios=[]
        for block in range(args.calibration_blocks):
            order=[('A',off),('B',candidate),('B',candidate),('A',off)] if rng.getrandbits(1) else [('B',candidate),('A',off),('A',off),('B',candidate)]
            rows=[]
            for label,binary in order:
                data=run(binary,'off','low95',size,seed)
                rows.append({**data['runs'][0],'label':label})
            if len({r['checksum'] for r in rows})!=1:raise RuntimeError('calibration mismatch')
            ratio=sum(r['elapsed_ns'] for r in rows if r['label']=='A')/sum(r['elapsed_ns'] for r in rows if r['label']=='B')
            ratios.append(ratio);raw.append({'size':size,'seed':seed,'block':block,'runs':rows,'ratio':ratio})
        calibration.append({'size':size,'seed':seed,'median_speedup':statistics.median(ratios),'ci95':median_ci(ratios)})
    write(out/'calibration.json',calibration);write(out/'calibration-raw.json',raw)
    approved=all(r['ci95']['low']>=1.02 for r in calibration)
    for site in profile['sites']:
        site['validated']=approved
        site['validation_speedup_lower']=min(r['ci95']['low'] for r in calibration)
    profile['validation']={'approved':approved,'independent_from_training':True,'cases':calibration}
    write(out/'validated-profile.json',profile)
    command([bolt,original,*base,'-cmov-branchify-runtime','-cmov-branchify-profile='+str(out/'validated-profile.json'),'-o',on],'runtime-optimize')
    log=(out/'runtime-optimize.log').read_text()
    injected='CMOV runtime: retained original kernel' in log
    if injected!=approved:raise RuntimeError('runtime injection and approval disagree')
    command(['nm','-S',on],'output-symbols')
    for symbol in ('cmov_kernel_v1','__bolt_cmov_branch_v1','cmov_batch_v1'):
        command(['objdump','-d','--disassemble='+symbol,on],symbol+'-disassembly')
    command(['readelf','--debug-dump=frames',on],'output-frames')
    smoke=[]
    for size in (4096,8192):
        for case in ('low95','uniform','shift','short-uniform1','threshold511','threshold512','threshold513','early-shift','calibration-alias','hot-prefix'):
            baseline=run(off,'guarded',case,size,71049)
            enabled=run(on,'guarded',case,size,71049)
            if baseline['runs'][0]['checksum']!=enabled['runs'][0]['checksum']:raise RuntimeError('smoke output mismatch')
            smoke.append({'size':size,'case':case,'baseline':baseline,'enabled':enabled})
    write(out/'smoke.json',smoke)
    rejected=dict(profile);rejected['sites']=[]
    write(out/'rejected-profile.json',rejected)
    reject=out/'rejected'
    command([bolt,original,*base,'-cmov-branchify-runtime','-cmov-branchify-profile='+str(out/'rejected-profile.json'),'-o',reject],'rejected')
    identity=pipeline.executable_hash(reject)==pipeline.executable_hash(off)
    if not identity:raise RuntimeError('static rejection changed executable sections')
    meta={'runtime_bolt_option_implemented':True,'injected':injected,
          'runtime_archive_sha256':protocol['runtime_archive_sha256'],
          'input_sha256':sha(original),'off_sha256':sha(off),'on_sha256':sha(on),
          'static_rejection_executable_identical':identity,
          'original_kernel_cmov':len(re.findall(r'\s+cmov[a-z]+\s',(out/'cmov_kernel_v1-disassembly.log').read_text())),
          'branch_kernel_cmov':len(re.findall(r'\s+cmov[a-z]+\s',(out/'__bolt_cmov_branch_v1-disassembly.log').read_text())),
          'calibration':calibration,'smoke_cases':len(smoke),
          'scope':'explicit cooperative SysV batch ABI v1, not arbitrary ELF interfaces'}
    write(out/'build.json',meta);print(json.dumps(meta,indent=2),flush=True)


if __name__=='__main__': main()
